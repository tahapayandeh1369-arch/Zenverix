/* ============================================================
   🌐 APPLY LANGUAGE - (تعریف قبل از استفاده)
============================================================ */
function applyLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);

    const langLabel = document.getElementById('langLabel');
    if (langLabel) {
        langLabel.textContent = lang === 'en' ? 'EN' : 'FA';
    }

    document.querySelectorAll('[data-key]').forEach(function (element) {
        const key = element.getAttribute('data-key');
        const translation = translations[lang]?.[key];
        if (translation !== undefined) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translation;
            } else if (element.tagName === 'SPAN' && element.parentElement?.classList?.contains('typed-text')) {
                element.textContent = translation;
            } else {
                element.innerHTML = translation;
            }
        }
    });

    if (window.typedInstance) {
        const heroSubtitle = document.querySelector('.typed-text');
        if (heroSubtitle) {
            const newText = translations[lang]?.['hero-subtitle'] || 'Developer & Creative Thinker';
            window.typedInstance.strings = [newText];
            window.typedInstance.reset();
        }
    }

    if (lang === 'fa') {
        document.documentElement.setAttribute('dir', 'rtl');
        document.documentElement.lang = 'fa';
        document.body.style.fontFamily = "'Vazirmatn', 'Poppins', Tahoma, sans-serif";
    } else {
        document.documentElement.setAttribute('dir', 'ltr');
        document.documentElement.lang = 'en';
        document.body.style.fontFamily = "'Poppins', 'Vazirmatn', Tahoma, sans-serif";
    }
}

