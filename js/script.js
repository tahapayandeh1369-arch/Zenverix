function performSearch() {
    const query = searchInput.value.toLowerCase().trim();
    const alertText = currentLanguage === 'en'
        ? 'Please enter a search term!'
        : 'لطفاً عبارت جستجو را وارد کنید!';
    const notFoundText = currentLanguage === 'en'
        ? 'No results found for:'
        : 'نتیجه‌ای برای عبارت یافت نشد:';

    if (!query) {
        alert(alertText);
        return;
    }

    const sections = document.querySelectorAll('section');
    let found = false;

    sections.forEach(function (section) {
        const text = section.textContent.toLowerCase();
        if (text.includes(query)) {
            section.scrollIntoView({
                behavior: 'smooth',
                block: 'start'
            });
            section.style.transition = 'background 0.5s ease';
            section.style.background = 'rgba(37, 99, 235, 0.08)';
            setTimeout(function () {
                section.style.background = '';
            }, 3000);
            found = true;
            return;
        }
    });

    if (!found) {
        alert(notFoundText + ' "' + query + '"');
    }

    searchInput.value = '';
}

